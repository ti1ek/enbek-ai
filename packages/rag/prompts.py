def _load_skill() -> str:
    """Load citation rules from kz-legal-citation-formatter SKILL.md."""
    import re
    from pathlib import Path
    skill_path = Path(__file__).parent.parent.parent / "skills" / "kz-legal-citation-formatter" / "SKILL.md"
    try:
        raw = skill_path.read_text(encoding="utf-8")
        raw = re.sub(r"^---.*?---\s*", "", raw, flags=re.DOTALL)
        return raw.strip()
    except Exception:
        return ""


